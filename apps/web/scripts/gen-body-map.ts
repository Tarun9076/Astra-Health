// Generates the flat body diagram (src/features/body/bodyMapPaths.ts) from the same anatomy model as
// the 3D view: a front view of the skin and of each organ system, traced with marching squares.
// Run with:  node scripts/gen-body-map.ts   (Node 23.6+ runs TypeScript directly)
import { writeFileSync } from 'node:fs'
import { DRAW_ORDER, ORGANS, SKIN, type Shape } from '../src/features/body/anatomy.ts'

const SCALE = 250 // SVG units per metre
const X0 = -0.36, TOP = 1.775 // left edge and top of the drawing, metres
const WIDTH = 0.72 * SCALE, HEIGHT = TOP * SCALE + 2
const STEP = 0.0025 // grid step, metres

const sx = (x: number) => (x - X0) * SCALE
const sy = (y: number) => (TOP - y) * SCALE

/** Front view: the smallest distance along each line of sight (negative = covered by the shape). */
function project(shape: Shape) {
  const x0 = shape.lo[0] - 2 * STEP, y0 = shape.lo[1] - 2 * STEP
  const nx = Math.ceil((shape.hi[0] + 2 * STEP - x0) / STEP) + 1
  const ny = Math.ceil((shape.hi[1] + 2 * STEP - y0) / STEP) + 1
  const dz = 0.003
  const v = new Float32Array(nx * ny)
  for (let j = 0; j < ny; j++) {
    for (let i = 0; i < nx; i++) {
      let best = Infinity
      for (let z = shape.lo[2]; z <= shape.hi[2]; z += dz) {
        const d = shape.d(x0 + i * STEP, y0 + j * STEP, z)
        if (d < best) best = d
        if (best < -dz) break
      }
      v[i + nx * j] = best
    }
  }
  return { x0, y0, nx, ny, v }
}

/** Closed outlines of the covered area (marching squares), as SVG path data. */
function trace(shape: Shape): string {
  const { x0, y0, nx, ny, v } = project(shape)
  const at = (i: number, j: number) => v[i + nx * j]
  const point = new Map<string, [number, number]>()
  const links = new Map<string, string[]>()
  const crossing = (key: string, ax: number, ay: number, va: number, bx: number, by: number, vb: number) => {
    if (!point.has(key)) {
      const t = va / (va - vb)
      point.set(key, [sx(x0 + (ax + t * (bx - ax)) * STEP), sy(y0 + (ay + t * (by - ay)) * STEP)])
    }
    return key
  }
  const link = (a: string, b: string) => {
    links.set(a, [...(links.get(a) ?? []), b])
    links.set(b, [...(links.get(b) ?? []), a])
  }
  for (let j = 0; j < ny - 1; j++) {
    for (let i = 0; i < nx - 1; i++) {
      const a = at(i, j), b = at(i + 1, j), c = at(i + 1, j + 1), d = at(i, j + 1)
      const edges: string[] = []
      if ((a < 0) !== (b < 0)) edges.push(crossing(`h${i},${j}`, i, j, a, i + 1, j, b))
      if ((b < 0) !== (c < 0)) edges.push(crossing(`v${i + 1},${j}`, i + 1, j, b, i + 1, j + 1, c))
      if ((d < 0) !== (c < 0)) edges.push(crossing(`h${i},${j + 1}`, i, j + 1, d, i + 1, j + 1, c))
      if ((a < 0) !== (d < 0)) edges.push(crossing(`v${i},${j}`, i, j, a, i, j + 1, d))
      if (edges.length === 2) link(edges[0], edges[1])
      else if (edges.length === 4) {
        // saddle: decide by the centre of the cell
        const centre = (a + b + c + d) / 4 < 0
        if (centre === (a < 0)) { link(edges[0], edges[1]); link(edges[2], edges[3]) }
        else { link(edges[0], edges[3]); link(edges[1], edges[2]) }
      }
    }
  }
  const seen = new Set<string>()
  const loops: [number, number][][] = []
  for (const startKey of links.keys()) {
    if (seen.has(startKey)) continue
    const loop: [number, number][] = []
    let prev = '', cur = startKey
    while (cur && !seen.has(cur)) {
      seen.add(cur)
      loop.push(point.get(cur)!)
      const next = (links.get(cur) ?? []).find((n) => n !== prev && !seen.has(n))
      prev = cur
      cur = next ?? ''
    }
    if (loop.length > 6) loops.push(simplify(loop, 0.3))
  }
  return loops.map((l) => 'M' + l.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z').join('')
}

/** Douglas–Peucker: drop points that change the outline by less than eps units. */
function simplify(pts: [number, number][], eps: number): [number, number][] {
  if (pts.length < 3) return pts
  const keep = new Uint8Array(pts.length)
  keep[0] = keep[pts.length - 1] = 1
  const stack: [number, number][] = [[0, pts.length - 1]]
  while (stack.length) {
    const [s, e] = stack.pop()!
    const [ax, ay] = pts[s], [bx, by] = pts[e]
    const len = Math.hypot(bx - ax, by - ay) || 1
    let worst = -1, at = -1
    for (let k = s + 1; k < e; k++) {
      const dist = Math.abs((bx - ax) * (ay - pts[k][1]) - (ax - pts[k][0]) * (by - ay)) / len
      if (dist > worst) { worst = dist; at = k }
    }
    if (worst > eps) { keep[at] = 1; stack.push([s, at], [at, e]) }
  }
  return pts.filter((_, k) => keep[k])
}

const started = Date.now()
const regions = DRAW_ORDER.map((id) => `  ${id}: '${trace(ORGANS[id])}',`)
const out = `// Generated by scripts/gen-body-map.ts from anatomy.ts (front view). Do not edit by hand.
export const BODY_VIEWBOX = '0 0 ${WIDTH.toFixed(0)} ${HEIGHT.toFixed(0)}'
export const SKIN_PATH = '${trace(SKIN)}'
export const REGION_PATHS: Record<string, string> = {
${regions.join('\n')}
}
`
writeFileSync(new URL('../src/features/body/bodyMapPaths.ts', import.meta.url), out)
console.log(`bodyMapPaths.ts: ${(out.length / 1024).toFixed(1)} KB in ${Date.now() - started} ms`)
